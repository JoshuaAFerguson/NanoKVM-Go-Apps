try:  # reuse appbase's glyphs for everything it already has
    from appbase import _FONT as _BASE  # type: ignore[attr-defined]
except ImportError:  # off-device tests
    _BASE = {}

GLYPHS: dict = {**_BASE, **_EXTRA}
_FALLBACK = GLYPHS.get("?")
_runs_cache: dict = {}


def _runs(ch: str) -> tuple:
    """Per glyph: tuple of (row, start_col, length) horizontal runs."""
    cached = _runs_cache.get(ch)
    if cached is not None:
        return cached
    rows = GLYPHS.get(ch) or GLYPHS.get(ch.upper()) or (_FALLBACK if ch != " " else None)
    runs = []
    for r, bits in enumerate(rows or ()):
        c = 0
        while c < 8:
            if bits >> c & 1:
                start = c
                while c < 8 and bits >> c & 1:
                    c += 1
                runs.append((r, start, c - start))
            else:
                c += 1
    result = tuple(runs)
    _runs_cache[ch] = result
    return result


def has_glyph(ch: str) -> bool:
    return ch == " " or ch in GLYPHS or ch.upper() in GLYPHS


def draw_text(fb, x: int, y: int, text: str, color: int, scale: int = 1) -> None:
    cx = x
    step = GLYPH_PX * scale
    for ch in text:
        for r, start, length in _runs(ch):
            fb.fill_rect(cx + start * scale, y + r * scale, length * scale, scale, color)
        cx += step


def text_width(text: str, scale: int = 1) -> int:
    return len(text) * GLYPH_PX * scale
